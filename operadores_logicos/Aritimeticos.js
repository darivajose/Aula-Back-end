// operadores aritméticos
// + adição
// - subtração
// * multiplicação
// / divisão
// % módulo (resto da divisão)
// ** exponenciação

let numero1 = 10
let numero2 = 5
 
console.log("Adição: " + (numero1 + numero2)) // 15
console.log("Subtração: " + (numero1 - numero2)) // 5
console.log("Multiplicação: " + (numero1 * numero2)) // 50
console.log("Divisão: " + (numero1 / numero2)) // 2
console.log("Módulo: " + (numero1 % numero2)) // 0
console.log("Exponenciação: " + (numero1 ** numero2)) // 100000

